"""Synthetic Pakistan customer-churn data generator.

Produces 7,000 schema-conformant synthetic records (`docs/PROJECT_SPEC.md`
§3.1, §3.3) from six customer archetypes, each with its own feature
distributions and conditional probabilities — not by copying or jittering
IBM rows (§3.2 point 2). Records are tagged `Source = "Pakistan-Synthetic"`
and `CustomerID` prefixed `PK-` for provenance (§3.2 point 1).

Archetypes (target share of the 7,000 records, per §3.3):

- Urban high-income postpaid-like (15%) — long tenure skew, two-year
  contracts, fiber-equivalent internet, low churn base rate.
- Urban middle-income (25%) — mixed contract types, moderate tenure and
  monthly spend.
- Urban low-income / price-sensitive (15%) — month-to-month, DSL or no
  internet, high price sensitivity -> higher churn base rate.
- Semi-urban family/shared plan (15%) — higher partner/dependents rate,
  multiple lines, mid tenure.
- Rural / lower connectivity (15%) — lower internet penetration, phone-only
  more common, shorter tenure.
- Young single urban, prepaid-like (15%) — short tenure, month-to-month,
  electronic payment, highest churn base rate.

Distributional assumptions (illustrative, not market research; documented
here per §3.2 point 5): tenure and monthly charges are drawn per-archetype
from truncated-normal distributions clipped to the IBM-observed ranges (0-72
months, $18.25-$118.75); payment-method mix is skewed per archetype (e.g.
mailed/electronic check dominate lower-income and rural segments, automatic
bank/card payment is more common in the high-income segment); service add-on
uptake is near-zero in the rural archetype and highest in the high-income and
young-urban archetypes. Total Charges = tenure x monthly charge + billing-
variance noise (§3.3), never a perfectly deterministic product.

Churn labels are generated by the shared latent-propensity mechanism in
`engine.py` (`docs/PROJECT_SPEC.md` §3.5): a logistic function of contract
type, charges, tenure, tech support, payment method, and family ties, plus
Gaussian noise and a per-archetype base-churn offset, then sampled as a
Bernoulli draw — so churn is realistic and learnable but never a
deterministic function of any single feature.

Reproducible: `RANDOM_SEED` (`ml/config.py`) drives every draw; re-running
this module produces byte-identical output.

Run directly: `python -m ml.data_generation.pakistan_generator`
"""

