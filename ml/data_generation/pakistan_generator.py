def generate(seed: int = PAKISTAN_SEED):
    return generate_country_dataset(
        archetypes=ARCHETYPES,
        total_records=SYNTHETIC_RECORDS_PER_COUNTRY,
        country_source_label="Pakistan-Synthetic",
        id_prefix="PK",
        seed=seed,
    )


def main() -> None:
    df = generate()
    # `_archetype` is internal provenance for validate.py's per-archetype
    # churn-rate table — not part of the schema contract (ML_SPEC.md §1),
    # so it is dropped from the persisted, schema-conformant CSV.
    df = df.drop(columns=["_archetype"])
    DATA_PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTPUT_PATH, index=False)
    print(f"Wrote {len(df)} Pakistan synthetic records to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
